/**
  * @brief This function handles System tick timer.
  */
void SysTick_Handler(void)
{
  /* USER CODE BEGIN SysTick_IRQn 0 */

  /* USER CODE END SysTick_IRQn 0 */
  HAL_IncTick();
  /* USER CODE BEGIN SysTick_IRQn 1 */
  /* SysTick 一拍两用：上方 HAL_IncTick() 维护 HAL 的 uwTick（HAL 延时/超时基准），
   * 此处 rt_tick_increase() 驱动 RT-Thread 系统节拍。调度器启动前
   * rt_thread_self() 返回 RT_NULL，此时跳过 RT-Thread 分支，避免在内核
   * 就绪前访问线程；rt_interrupt_enter/leave 维护中断嵌套计数。 */
  if (rt_thread_self() != RT_NULL)
  {
    rt_interrupt_enter();
    rt_tick_increase();
    rt_interrupt_leave();
  }
  /* USER CODE END SysTick_IRQn 1 */
}

